-- V4: 인증 제출, 투표, 리액션, 읽음, 코인 거래 (api.md 6장, 7장 보상 규칙, 10장)

CREATE TABLE proofs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mission_id     BIGINT       NOT NULL,
    user_id        BIGINT       NOT NULL,
    media_url      VARCHAR(512),
    thumbnail_url  VARCHAR(512),
    media_type     VARCHAR(10)  NOT NULL,            -- IMAGE | VIDEO | TEXT
    text           VARCHAR(300),
    status         VARCHAR(10)  NOT NULL,            -- PENDING | APPROVED | REJECTED | EXPIRED
    finalized_at   TIMESTAMP(6) WITH TIME ZONE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_proofs_mission FOREIGN KEY (mission_id) REFERENCES missions (id) ON DELETE CASCADE,
    CONSTRAINT fk_proofs_user    FOREIGN KEY (user_id)    REFERENCES users (id)    ON DELETE CASCADE
);

-- 같은 미션에 한 사람의 대기/승인 인증은 1개만 (거절·만료 후 재제출 허용)
CREATE UNIQUE INDEX uk_proofs_mission_user_open ON proofs (mission_id, user_id) WHERE status IN ('PENDING', 'APPROVED');
CREATE INDEX idx_proofs_mission ON proofs (mission_id);
CREATE INDEX idx_proofs_user_status ON proofs (user_id, status);
CREATE INDEX idx_proofs_created ON proofs (created_at DESC);

CREATE TABLE proof_votes (
    proof_id   BIGINT      NOT NULL,
    voter_id   BIGINT      NOT NULL,
    vote       VARCHAR(10) NOT NULL,                 -- APPROVE | REJECT
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (proof_id, voter_id),
    CONSTRAINT fk_proof_votes_proof FOREIGN KEY (proof_id) REFERENCES proofs (id) ON DELETE CASCADE,
    CONSTRAINT fk_proof_votes_voter FOREIGN KEY (voter_id) REFERENCES users (id)  ON DELETE CASCADE
);

CREATE TABLE proof_reactions (
    proof_id   BIGINT      NOT NULL,
    user_id    BIGINT      NOT NULL,
    emoji      VARCHAR(16) NOT NULL,
    PRIMARY KEY (proof_id, user_id, emoji),
    CONSTRAINT fk_proof_reactions_proof FOREIGN KEY (proof_id) REFERENCES proofs (id) ON DELETE CASCADE,
    CONSTRAINT fk_proof_reactions_user  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE CASCADE
);

CREATE TABLE proof_views (
    proof_id   BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    viewed_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (proof_id, user_id),
    CONSTRAINT fk_proof_views_proof FOREIGN KEY (proof_id) REFERENCES proofs (id) ON DELETE CASCADE,
    CONSTRAINT fk_proof_views_user  FOREIGN KEY (user_id)  REFERENCES users (id)  ON DELETE CASCADE
);

-- 코인 변동 이력 (지급·구매·대체 지급). 상점 구매는 보상·상점 마이그레이션에서 reason 을 추가로 사용한다.
CREATE TABLE coin_transactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL,
    amount         INTEGER     NOT NULL,
    balance_after  INTEGER     NOT NULL,
    reason         VARCHAR(30) NOT NULL,             -- MISSION_REWARD | PURCHASE | ITEM_DUPLICATE_COMPENSATION
    ref_id         BIGINT,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_coin_tx_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_coin_tx_user_created ON coin_transactions (user_id, created_at DESC);

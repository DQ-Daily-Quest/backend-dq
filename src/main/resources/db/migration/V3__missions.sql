-- V3: 미션 템플릿(APP 미션 풀), 미션 (api.md 5장, 10장)
-- reward_item_id 는 items 테이블이 생기는 마이그레이션(보상·상점)에서 FK를 추가한다.

CREATE TABLE mission_templates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content         VARCHAR(100) NOT NULL,
    reward_item_id  BIGINT,
    active          BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE missions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT       NOT NULL,
    type            VARCHAR(10)  NOT NULL,            -- APP | MEMBER
    template_id     BIGINT,
    content         VARCHAR(100) NOT NULL,
    reward_type     VARCHAR(10)  NOT NULL,            -- ITEM | COIN
    reward_item_id  BIGINT,
    reward_coins    INTEGER,
    created_by      BIGINT,                           -- MEMBER 미션 작성자, APP 은 NULL
    date            DATE,                             -- APP 미션의 KST 날짜, MEMBER 는 NULL
    due_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_missions_room     FOREIGN KEY (room_id)     REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT fk_missions_template FOREIGN KEY (template_id) REFERENCES mission_templates (id),
    CONSTRAINT fk_missions_creator  FOREIGN KEY (created_by)  REFERENCES users (id) ON DELETE SET NULL
);

-- 룸마다 하루에 APP 미션 1개만 (스케줄러·lazy 생성 경합 방지)
CREATE UNIQUE INDEX uk_missions_room_date_app ON missions (room_id, date) WHERE type = 'APP';
CREATE INDEX idx_missions_room_due ON missions (room_id, due_at);

